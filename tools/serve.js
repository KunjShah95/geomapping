/**
 * Dev server: static files + tile pyramid, with .env support.
 *
 *   node --env-file=.env tools/serve.js
 *   -> http://127.0.0.1:8777/web/index.html
 *
 * Serves /tiles/** and /web/** like `python -m http.server`, but additionally
 * generates /config.js from the environment so browser code can pick up keys
 * without the secret ever being hardcoded in the HTML.
 *
 * Only variables named in CLIENT_EXPOSE are exposed to the browser. Keep that
 * list empty unless a key is meant to be public, and restrict any public key by
 * HTTP referrer in the Google Cloud console.
 */
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const PORT = Number(process.env.PORT || 8777);
const HOST = process.env.HOST || '127.0.0.1';

const exposeNames = (process.env.CLIENT_EXPOSE || '')
  .split(',')
  .map(s => s.trim())
  .filter(Boolean);

const exposed = {};
const withheld = [];
for (const name of exposeNames) {
  if (process.env[name]) exposed[name] = process.env[name];
  else withheld.push(name);
}

// Any key-looking variable that exists but is NOT exposed, for the startup log.
const looksSecret = n => /(KEY|TOKEN|SECRET|PASSWORD|CREDENTIAL)/i.test(n);
const presentButHidden = Object.keys(process.env)
  .filter(n => looksSecret(n) && !exposeNames.includes(n) && process.env[n])
  .sort();

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.geojson': 'application/geo+json',
  '.pgw': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.webmanifest': 'application/manifest+json; charset=utf-8'
};

const configJs = () =>
  `// generated by tools/serve.js - do not edit\n` +
  `window.ENV = Object.freeze(${JSON.stringify(exposed, null, 2)});\n`;

const SECURITY_HEADERS = {
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'SAMEORIGIN',
  'Referrer-Policy': 'strict-origin-when-cross-origin'
};

const send = (res, code, type, body) => {
  res.writeHead(code, {
    'Content-Type': type,
    'Content-Length': Buffer.byteLength(body),
    'Cache-Control': 'no-store',
    ...SECURITY_HEADERS
  });
  res.end(body);
};

const server = http.createServer((req, res) => {
  let pathname;
  try {
    pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  } catch {
    return send(res, 400, 'text/plain', 'bad request');
  }

  if (pathname === '/config.js') return send(res, 200, TYPES['.js'], configJs());

  // serve /web/* at the root too, so /index.html works
  if (pathname === '/' || pathname === '/index.html') pathname = '/web/index.html';
  // the service worker must be served from the root to control /tiles_dp2021 and /data
  if (pathname === '/sw.js') pathname = '/web/sw.js';

  // Only the folders the viewers actually load are public. Everything else in
  // the project - .env (live keys), tools/, work/, the client's source PDFs -
  // stays private, as does any dot-file or dot-folder anywhere in the path.
  const PUBLIC = ['/web/', '/data/', '/tiles_dp2021/', '/tiles/'];
  if (!PUBLIC.some(p => pathname.startsWith(p)) ||
      pathname.split('/').some(seg => seg.startsWith('.'))) {
    return send(res, 404, 'text/plain', 'not found');
  }

  const file = path.resolve(path.join(ROOT, pathname));
  // Strict containment check: file must be ROOT or a descendant, not a sibling
  // whose name merely starts with ROOT (e.g. ROOT-evil).
  if (file !== ROOT && !file.startsWith(ROOT + path.sep)) {
    return send(res, 403, 'text/plain', 'forbidden');
  }
  let stat;
  try { stat = fs.statSync(file); } catch { return send(res, 404, 'text/plain', 'not found: ' + pathname); }
  if (!stat.isFile()) {
    return send(res, 404, 'text/plain', 'not found: ' + pathname);
  }

  const type = TYPES[path.extname(file).toLowerCase()] || 'application/octet-stream';
  res.writeHead(200, {
    'Content-Type': type,
    'Cache-Control': type.startsWith('image/') ? 'public, max-age=3600' : 'no-store',
    ...SECURITY_HEADERS
  });
  fs.createReadStream(file).pipe(res);
});

server.listen(PORT, HOST, () => {
  console.log(`serving ${ROOT}`);
  console.log(`  http://${HOST}:${PORT}/web/index.html`);
  console.log(`  client-exposed: ${Object.keys(exposed).join(', ') || '(none)'}`);
  if (withheld.length) console.log(`  WARN in CLIENT_EXPOSE but unset in .env: ${withheld.join(', ')}`);
  if (presentButHidden.length) {
    console.log(`  server-only secrets (not sent to browser): ${presentButHidden.join(', ')}`);
  }
});
